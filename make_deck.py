# ───── Смешанный текст (русский + иврит): каждый ивритский фрагмент изолируется <bdi dir=rtl>,
# чтобы соседние фрагменты, разделённые «;», «,», «—», не склеивались и не переставлялись.
HE_RUN = re.compile(r'[\u0590-\u05FF]+(?:[ ][\u0590-\u05FF]+)*[?!]?')
def bidi(text):
    return HE_RUN.sub(lambda m: f'<bdi dir="rtl">{m.group(0)}</bdi>', text)

def gov_html(r):
    t = GOV.get(r) or GOV.get(GOV_BASE.get(r))
    if not t: return ""
    items = []
    for it in t.split("; "):
        if " — " in it:
            he, ru = it.split(" — ", 1)
            items.append(f'<div class="gi"><bdi class="gh" dir="rtl">{he}</bdi> — {bidi(ru)}</div>')
        else:
            items.append(f'<div class="gi">{it}</div>')
    return '<div class="gov"><div class="gt">управление</div>' + "".join(items) + '</div>'

