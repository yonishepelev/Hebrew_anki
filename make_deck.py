import unicodedata
VOW = {'\u05B4','\u05B5','\u05B6','\u05B7','\u05B8','\u05B9','\u05BB','\u05C7'}  # full vowels
HATAF = {'\u05B1','\u05B2','\u05B3'}
GUTT = set('אהחע')
def clusters(w):
    out=[]
    for ch in w:
        if unicodedata.combining(ch) and out: out[-1]+=ch
        else: out.append(ch)
    return out
def nuclei(w):
    c=clusters(w); res=[]
    for i,cl in enumerate(c):
        base=cl[0]; marks=set(cl[1:])
        if not ('\u05D0'<=base<='\u05EA'): continue
        if base=='ו' and ('\u05BC' in marks or '\u05B9' in marks) and not (marks & (VOW-{'\u05B9'})):
            # shuruq / holam male: belongs to previous consonant if it has no vowel
            if i>0 and not (set(c[i-1][1:]) & (VOW|HATAF)) and '\u05BC' in marks and len(marks)==1 or \
               i>0 and '\u05B9' in marks and not (set(c[i-1][1:]) & (VOW|HATAF)):
                res.append((i-1,i,'o' if '\u05B9' in marks else 'u')); continue
            if '\u05BC' in marks and len(marks)==1 and i==0: res.append((i,i,'u')); continue
        v = marks & VOW
        if v:
            # furtive patah on final guttural
            if i==len(c)-1 and '\u05B7' in v and base in 'חעה' and i>0:
                prev=c[i-1]
                if (set(prev[1:]) & VOW) or prev[0] in 'וי': continue
            res.append((i,i,v.pop()))
    return c,res
PATAH,SEGOL,HIRIQ,QAMATS,TSERE,HOLAM='\u05B7','\u05B6','\u05B4','\u05B8','\u05B5','\u05B9'
def auto_milel(w):
    c,n=nuclei(w)
    if len(n)<2: return None
    last=n[-1]; pen=n[-2]
    tail=c[last[1]+1:]
    tail_bases=''.join(x[0] for x in tail)
    # segolate / -ֶת : final segol not followed by mater ה
    if last[2]==SEGOL and tail_bases not in ('ה',''):
        return 'segol'
    # -ַיִם / -ַיִת / -ַיִן / ַיִץ
    if last[2]==HIRIQ and c[last[0]][0]=='י' and pen[2] in (PATAH,QAMATS): return 'ayim'
    # guttural segolates: CeCaC / CaCaC with guttural, exactly 2 nuclei
    if len(n)==2 and last[2]==PATAH and pen[2] in (SEGOL,PATAH) and tail_bases and \
       (c[last[0]][0] in GUTT or tail_bases[-1] in GUTT): return 'gutt'
    # past 1/2 person suffixes
    if re.search('(תִּי|תָּ|תָ|נוּ)$', re.sub('[\u05BC]','\u05BC',w)) : return 'suffix'
    return None
def mark(w, milel):
    c,n=nuclei(w)
    if len(n)<2: return w
    a,b,_ = n[-2] if milel else n[-1]
    return ''.join(c[:a])+'<span class="st">'+''.join(c[a:b+1])+'</span>'+''.join(c[b+1:])

